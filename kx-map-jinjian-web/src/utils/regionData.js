/**
 * 获取指定省份下的所有城市
 * @param {string} provinceCode - 省份编码
 * @returns {Array<{code: string, name: string}>}
 */
export function getCities(provinceCode) {
  return cityMap[provinceCode] || []
}

/**
 * 获取指定城市下的所有区县
 * @param {string} cityCode - 城市编码
 * @returns {Array<{code: string, name: string}>}
 */
export function getDistricts(cityCode) {
  return districtMap[cityCode] || []
}

/**
 * 根据名称查找省份编码
 * @param {string} name - 省份名称
 * @returns {string|null}
 */
export function findProvinceCode(name) {
  const p = provinces.find(item => item.name === name)
  return p ? p.code : null
}

/**
 * 根据名称和父级编码查找城市编码
 * @param {string} name - 城市名称
 * @param {string} provinceCode - 省份编码
 * @returns {string|null}
 */
export function findCityCode(name, provinceCode) {
  const cities = getCities(provinceCode)
  const c = cities.find(item => item.name === name)
  return c ? c.code : null
}

/**
 * 根据名称和父级编码查找区县编码
 * @param {string} name - 区县名称
 * @param {string} cityCode - 城市编码
 * @returns {string|null}
 */
export function findDistrictCode(name, cityCode) {
  const districts = getDistricts(cityCode)
  const d = districts.find(item => item.name === name)
  return d ? d.code : null
}

export { provinces, cityMap, districtMap }
export default { provinces, cityMap, districtMap, getCities, getDistricts, findProvinceCode, findCityCode, findDistrictCode }
