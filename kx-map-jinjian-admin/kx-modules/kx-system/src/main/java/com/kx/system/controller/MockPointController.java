    /**
     * 构建一个 Feature 对象，ring 为 [lon,lat] 点数组
     */
    private Features buildFeature(String code, String name, String type, double[] center, double[][] ring) {
        Features feature = new Features();

        Properties props = new Properties();
        props.setCode(code);
        props.setName(name);
        props.setType(type);
        props.setCenter(Arrays.asList(center[0], center[1]));
        feature.setProperties(props);

        Geometry geometry = new Geometry();
        // MultiPolygon coords: [ polygon[ ring[ point ] ] ]
        geometry.setCoordinates(Collections.singletonList(Collections.singletonList(Arrays.asList(ring))));
        feature.setGeometry(geometry);

        return feature;
    }
